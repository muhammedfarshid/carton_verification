def grid(xs_per_col, rows_per_col):
    """Boxes for column-major grid layouts: xs=(x1,x2), rows=[y0,y1,...]."""
    out = []
    for (x1, x2), ys in zip(xs_per_col, rows_per_col):
        out += [[x1, a, x2, b] for a, b in zip(ys[:-1], ys[1:])]
    return out


